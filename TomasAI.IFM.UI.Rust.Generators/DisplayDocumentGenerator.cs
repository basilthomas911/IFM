using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using System.Collections.Immutable;
using System.Text;

namespace TomasAI.IFM.UI.Rust.Generators;

/// <summary>Builds strongly typed display accessors from document and row construction sites.</summary>
[Generator]
public sealed class DisplayDocumentGenerator : IIncrementalGenerator
{
 public void Initialize(IncrementalGeneratorInitializationContext context) {
  var types=context.SyntaxProvider.CreateSyntaxProvider(
   static (node,_)=>node is InvocationExpressionSyntax or AnonymousObjectCreationExpressionSyntax,
   static (ctx,_)=>FindTypes(ctx)).SelectMany(static (items,_)=>items).Collect();
  context.RegisterSourceOutput(types,static (output,roots)=>Emit(output,roots));
 }
 static ImmutableArray<ITypeSymbol> FindTypes(GeneratorSyntaxContext context) {
  if(context.Node is AnonymousObjectCreationExpressionSyntax anonymous){
   var assembly=context.SemanticModel.Compilation.AssemblyName;
   if(assembly is "TomasAI.IFM.UI.Rust.Bridge.Net" or "TomasAI.IFM.UI.Rust.Benchmarks"){
    var shape=context.SemanticModel.GetTypeInfo(anonymous).Type;return shape is null?[]:[shape];
   }
   return [];
  }
  var call=(InvocationExpressionSyntax)context.Node;
  var method=context.SemanticModel.GetSymbolInfo(call).Symbol as IMethodSymbol;
  if(method is null)return [];
  var owner=method.ContainingType.ToDisplayString();
  if(owner is not ("TomasAI.IFM.UI.Rust.Bridge.Net.BridgeDocument" or "TomasAI.IFM.UI.Rust.Bridge.Net.BridgeWire" or "TomasAI.IFM.UI.Rust.Bridge.Net.DisplayDescriptors")
   && !(method.ContainingNamespace.ToDisplayString()=="TomasAI.IFM.UI.Rust.Bridge.Net" && method.Name is "Row" or "Add" or "Properties"))return [];
  var result=ImmutableArray.CreateBuilder<ITypeSymbol>();
  foreach(var argument in call.ArgumentList.Arguments)if(context.SemanticModel.GetTypeInfo(argument.Expression).Type is {} type)result.Add(type);
  foreach(var type in method.TypeArguments)result.Add(type);
  return result.ToImmutable();
 }
 static void Emit(SourceProductionContext output,ImmutableArray<ITypeSymbol> roots) {
  var seen=new HashSet<ITypeSymbol>(SymbolEqualityComparer.Default);
  var shapes=new List<INamedTypeSymbol>();
  void Visit(ITypeSymbol type,int depth) {
   if(depth>24||!seen.Add(type))return;
   if(type is IArrayTypeSymbol array){Visit(array.ElementType,depth+1);return;}
   if(type is not INamedTypeSymbol named||named.IsRefLikeType||named.TypeKind is TypeKind.Enum or TypeKind.Delegate||named.SpecialType!=SpecialType.None)return;
   foreach(var argument in named.TypeArguments)Visit(argument,depth+1);
   if(named.TypeArguments.Any(a=>a.TypeKind==TypeKind.TypeParameter)||named.IsUnboundGenericType)return;
   if(named.ContainingNamespace.ToDisplayString().StartsWith("System",StringComparison.Ordinal)&&named.Name!="KeyValuePair"||named.IsTupleType)return;
   if(named.AllInterfaces.Any(i=>i.OriginalDefinition.SpecialType==SpecialType.System_Collections_Generic_IEnumerable_T))return;
   if(!named.IsAnonymousType && (named.DeclaredAccessibility is not (Accessibility.Public or Accessibility.Internal)||named.ContainingType?.DeclaredAccessibility==Accessibility.Private))return;
   var members=Members(named).ToArray();if(members.Length==0)return;
   shapes.Add(named);foreach(var member in members)Visit(member.Type,depth+1);
  }
  foreach(var root in roots)Visit(root,0);
  var code=new StringBuilder("// <auto-generated/>\n#pragma warning disable CS0618 // Preserve existing serialized compatibility members.\n#nullable enable\nnamespace TomasAI.IFM.UI.Rust.Generated;\ninternal static class DisplayRegistration {\n[global::System.Runtime.CompilerServices.ModuleInitializer] internal static void Register() {\n");
  foreach(var shape in shapes) {
   var members=Members(shape).ToArray();
   var marker=Marker(shape,0);if(marker is null)continue;
   code.Append("global::TomasAI.IFM.UI.Rust.Bridge.Net.DisplayDescriptors.Register(").Append(marker).Append(", static () => new global::TomasAI.IFM.UI.Rust.Bridge.Net.DisplayProperty[] {\n");
   for(int i=0;i<members.Length;i++) {
    var member=members[i];
    code.Append("global::TomasAI.IFM.UI.Rust.Bridge.Net.DisplayDescriptors.Property(").Append(marker).Append(", ")
     .Append(SymbolDisplay.FormatLiteral(member.Name,true)).Append(", static value => value.@").Append(member.Name)
     .Append(", ").Append(SymbolDisplay.FormatLiteral(member.GetAttributes().FirstOrDefault(a=>a.AttributeClass?.ToDisplayString()=="System.ComponentModel.DisplayNameAttribute")?.ConstructorArguments.FirstOrDefault().Value as string ?? member.Name,true))
     .Append(", ").Append(member.GetAttributes().Any(a=>a.AttributeClass?.ToDisplayString()=="System.ComponentModel.BrowsableAttribute" && a.ConstructorArguments.FirstOrDefault().Value is false)?"false":"true")
     .Append(", ").Append(SymbolDisplay.FormatLiteral(member.GetAttributes().FirstOrDefault(a=>a.AttributeClass?.ToDisplayString()=="MessagePack.KeyAttribute")?.ConstructorArguments.FirstOrDefault().Value as string ?? member.Name,true)).Append(')')
     .Append(i+1==members.Length?"});\n":",\n");
   }
  }
  code.Append("}\n}\n");output.AddSource("DisplayRegistration.g.cs",code.ToString());
 }
 static IEnumerable<IPropertySymbol> Members(INamedTypeSymbol type) {
  var seen=new HashSet<string>(StringComparer.Ordinal);
  for(INamedTypeSymbol? current=type;current is not null&&(SymbolEqualityComparer.Default.Equals(current,type)||!current.ContainingNamespace.ToDisplayString().StartsWith("System",StringComparison.Ordinal));current=current.BaseType)
   foreach(var member in current.GetMembers().OfType<IPropertySymbol>()) {
    if(member.IsStatic||member.IsIndexer||member.GetMethod?.DeclaredAccessibility!=Accessibility.Public||!seen.Add(member.Name)||member.Type.IsRefLikeType)continue;
    if(member.GetAttributes().Any(a=>a.AttributeClass?.ToDisplayString()=="System.Text.Json.Serialization.JsonIgnoreAttribute" && (!a.NamedArguments.Any()||a.NamedArguments.Any(p=>p.Key=="Condition"&&(int?)p.Value.Value==1))))continue;
    yield return member;
   }
 }
 static bool ContainsAnonymous(ITypeSymbol type)=>type is INamedTypeSymbol n&&(n.IsAnonymousType||n.TypeArguments.Any(ContainsAnonymous))||type is IArrayTypeSymbol a&&ContainsAnonymous(a.ElementType);
 static string? Marker(ITypeSymbol type,int depth) {
  if(depth>16)return null;
  if(type is INamedTypeSymbol {IsAnonymousType:true} anonymous) {
   var fields=new List<string>();
   foreach(var property in Members(anonymous)){var nested=Marker(property.Type,depth+1);if(nested is null)return null;fields.Add("@"+property.Name+" = "+nested);}
   return "new { "+string.Join(", ",fields)+" }";
  }
  if(type is IArrayTypeSymbol array && ContainsAnonymous(array.ElementType)) {
   var item=Marker(array.ElementType,depth+1);return item is null?null:"new[] { "+item+" }";
  }
  if(type is INamedTypeSymbol generic && generic.IsGenericType && generic.TypeArguments.Any(ContainsAnonymous)) {
   var arguments=generic.TypeArguments.Select(t=>Marker(t,depth+1)).ToArray();if(arguments.Any(a=>a is null))return null;
   var method=generic.OriginalDefinition.ToDisplayString() switch {
    "System.Collections.Generic.IEnumerable<T>"=>"SequenceMarker",
    "System.Collections.Generic.IReadOnlyList<T>"=>"ReadOnlyListMarker",
    "System.Collections.Generic.List<T>"=>"ListMarker",
    "System.Collections.Generic.Dictionary<TKey, TValue>"=>"DictionaryMarker",
    "System.Collections.Generic.IReadOnlyDictionary<TKey, TValue>"=>"ReadOnlyDictionaryMarker",
    _=>null
   };
   return method is null?null:"global::TomasAI.IFM.UI.Rust.Bridge.Net.DisplayDescriptors."+method+"("+string.Join(", ",arguments)+")";
  }
  if(type.TypeKind==TypeKind.TypeParameter||type is IErrorTypeSymbol)return null;
  if(type is INamedTypeSymbol check)for(var current=check;current is not null;current=current.ContainingType)
    if(current.DeclaredAccessibility is Accessibility.Private or Accessibility.Protected or Accessibility.ProtectedAndInternal)return null;
  return "default("+type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)+")!";
 }
}
