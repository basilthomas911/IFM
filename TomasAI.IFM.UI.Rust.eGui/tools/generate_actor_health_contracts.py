"""Generate concrete actor HTTP health records from the shared C# UI contract."""
from pathlib import Path
import re,argparse
ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT.parent/'TomasAI.IFM.UI.Net.Models/Operations/ActorHealthSnapshot.cs'
OUT=ROOT/'src/models/actor_health.rs'
source=SOURCE.read_text()
records={};aliases={}
for match in re.finditer(r'public (?:sealed )?record (\w+)(?:\s*:\s*(\w+))?\s*([;{])',source):
 name,base,start=match.groups()
 if start==';':aliases[name]=base;continue
 depth=1;end=match.end()
 while depth:
  if source[end]=='{':depth+=1
  elif source[end]=='}':depth-=1
  end+=1
 records[name]=re.findall(r'public ([\w<>?]+) (\w+) \{ get; init; \}',source[match.end():end-1])
def snake(name):return re.sub(r'([a-z0-9])([A-Z])',r'\1_\2',re.sub(r'(.)([A-Z][a-z]+)',r'\1_\2',name)).lower()
def rust_type(kind):
 kind=kind.rstrip('?')
 if kind.startswith('IReadOnlyList<'):return 'Vec<'+kind[len('IReadOnlyList<'):-1]+'>'
 return {'int':'i32','long':'i64','double':'f64','bool':'bool'}.get(kind,kind if kind in records or kind in aliases else 'String')
lines=['//! Generated by tools/generate_actor_health_contracts.py from UI.Net.Models/Operations/ActorHealthSnapshot.cs.',
 'use serde::Deserialize;','use std::collections::BTreeMap;','use super::{cells::{Cell,Cells,ScalarCell},health_fields::{Present,HealthFields,key,scalar}};']
for name,base in aliases.items():lines.append(f'pub type {name}={base};')
for name,fields in records.items():
 lines+=['#[derive(Clone,Debug,Default,Deserialize)]',f'pub struct {name} {{']
 for kind,field in fields:
  camel=field[0].lower()+field[1:]
  lines+=[f'    #[serde(default,rename="{camel}",alias="{field}")]',f'    pub {snake(field)}:Present<{rust_type(kind)}>,']
 lines+=['}',f'impl Cells for {name} {{',"    fn cell(&self,column:&str)->Cell<'_>{match column{"]
 for kind,field in fields:
  if not rust_type(kind).startswith('Vec<') and kind.rstrip('?') not in records and kind.rstrip('?') not in aliases:lines+=[f'        "{field}"|"{field[0].lower()+field[1:]}"=>self.{snake(field)}.scalar_cell(),']
 lines+=['        _=>Cell::Missing,','    }}','}',f'impl HealthFields for {name} {{','    fn fields(&self,prefix:&str,output:&mut BTreeMap<String,String>){']
 for kind,field in fields:
  var=snake(field);expr=f'key(prefix,"{field}")'
  if rust_type(kind).startswith('Vec<'):
   lines+=[f'        if matches!(self.{var},Present::Null){{output.insert({expr},String::new());}}']
  elif kind.rstrip('?') in records or kind.rstrip('?') in aliases:
   lines+=[f'        if !self.{var}.is_missing(){{self.{var}.fields(&{expr},output);}}']
  else:lines+=[f'        scalar(&self.{var},{expr},output);']
 lines+=['    }','}']
output='\n'.join(lines)+'\n'
import subprocess
output=subprocess.run(['rustfmt','--edition','2024','--emit','stdout'],input=output,text=True,capture_output=True,check=True).stdout
parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
if args.check:
 if OUT.read_text()!=output:raise SystemExit('Actor HTTP health contracts are stale.')
else:OUT.write_text(output)
print(f'{len(records)} actor health record types, {sum(map(len,records.values()))} concrete fields')
