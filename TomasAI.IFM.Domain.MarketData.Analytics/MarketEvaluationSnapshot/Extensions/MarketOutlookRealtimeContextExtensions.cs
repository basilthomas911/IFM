/// <summary>Exposes readonly MarketOutlookRealtime Realtime context properties.</summary>
public static class MarketOutlookRealtimeContextExtensions
{
    extension(IRealtimeActorContext<MarketOutlookRealtimeActor> context)
    {
        /// <summary>Gets the domain-specific typed context.</summary>
        public IMarketOutlookRealtimeContext DomainContext =>
            IsArgumentNull.Set(context as IMarketOutlookRealtimeContext, nameof(context))!;
        /// <summary>Gets the Supervisor service retained by the typed context.</summary>
        public IActorSupervisor Supervisor => context.DomainContext.Supervisor;
        /// <summary>Gets the DbFactory service retained by the typed context.</summary>
        public IDbContextFactory DbFactory => context.DomainContext.DbFactory;
        /// <summary>Gets the Logger service retained by the typed context.</summary>
        public ILogger<MarketOutlookRealtimeActor> Logger => context.DomainContext.Logger;
    }
}
