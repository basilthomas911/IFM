"""Derive the synchronous adapter from the audited async parser. Keep field
validation, budget and byte-boundary logic identical; only I/O/yields differ.
"""
from pathlib import Path
root = Path(__file__).resolve().parents[1]
p = root / "vendor/dbn/src/decode/dbn"
s = (p / "streaming.rs").read_text()
s = s.replace("use tokio::io::{AsyncRead, AsyncReadExt, Take};", "use std::io::{Read, Take};")
s = s.replace("AsyncRead + Unpin", "Read")
s = s.replace("tokio::task::yield_now().await;", "std::thread::yield_now();")
s = s.replace("async fn", "fn").replace(".await", "")
s = "// Generated by qualification/Generate-SyncMetadata.py; edit streaming.rs.\n" + s
(p / "streaming_sync.rs").write_text(s)

import subprocess
subprocess.run(["rustfmt", "--edition", "2021", str(p / "streaming_sync.rs")], check=True)
